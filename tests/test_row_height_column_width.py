import openpyxl
from openpyxl.styles import Alignment
from app.renderer.fast_html_renderer import FastHtmlRenderer
from app.engine.template_processor import TemplateProcessor
from app.renderer.chrome_cdp_pool import ChromeCdpPool

def test_column_widths_to_colgroup():
    """Verify that openpyxl column widths are mapped to <colgroup><col style='width: ...pt;'> and table width."""
    wb = openpyxl.Workbook()
    ws = wb.active
    ws["A1"] = "Col A"
    ws["B1"] = "Col B"
    ws["C1"] = "Col C"

    ws.column_dimensions["A"].width = 16.0
    ws.column_dimensions["B"].width = 34.0
    ws.column_dimensions["C"].width = 10.0

    html_out = FastHtmlRenderer.render(ws)

    # 16.0 chars -> round(16*7 + 5)*0.75 = 117 * 0.75 = 87.75pt
    assert '<col style="width: 87.75pt;" />' in html_out
    # 34.0 chars -> round(34*7 + 5)*0.75 = 243 * 0.75 = 182.25pt
    assert '<col style="width: 182.25pt;" />' in html_out
    # 10.0 chars -> round(10*7 + 5)*0.75 = 75 * 0.75 = 56.25pt
    assert '<col style="width: 56.25pt;" />' in html_out

    # Total width: 87.75 + 182.25 + 56.25 = 326.25pt
    assert 'table-layout: fixed; width: 326.25pt' in html_out

def test_hidden_column_handling():
    """Verify that hidden columns get width: 0, display: none and their cells are hidden."""
    wb = openpyxl.Workbook()
    ws = wb.active
    ws["A1"] = "Visible A"
    ws["B1"] = "Hidden B"
    ws["C1"] = "Visible C"

    ws.column_dimensions["A"].width = 20.0
    ws.column_dimensions["B"].width = 25.0
    ws.column_dimensions["B"].hidden = True
    ws.column_dimensions["C"].width = 15.0

    html_out = FastHtmlRenderer.render(ws)

    # Col B in colgroup should be hidden
    assert '<col style="width: 0pt; display: none;" />' in html_out
    # Cell B1 should have display: none
    assert 'display: none' in html_out
    # Total width should exclude Col B: 20 -> 108.75pt, 15 -> 82.5pt = 191.25pt
    assert 'width: 191.25pt' in html_out

def test_row_heights_and_hidden_rows():
    """Verify row heights are emitted as <tr style='height: ...pt;'> and hidden rows get display: none."""
    wb = openpyxl.Workbook()
    ws = wb.active
    ws["A1"] = "Row 1 (35pt)"
    ws["A2"] = "Row 2 (Hidden)"
    ws["A3"] = "Row 3 (Default)"

    ws.row_dimensions[1].height = 35.0
    ws.row_dimensions[2].hidden = True
    # Row 3 will use defaultRowHeight (15.0pt)

    html_out = FastHtmlRenderer.render(ws)

    assert '<tr style="height: 35.0pt;">' in html_out
    assert '<tr style="display: none;">' in html_out
    assert '<tr style="height: 15.0pt;">' in html_out

def test_vertical_align_and_wrap_text():
    """Verify Excel alignment ('center' -> 'middle', wrap_text) is converted properly."""
    wb = openpyxl.Workbook()
    ws = wb.active
    ws["A1"] = "Centered Text"
    ws["A1"].alignment = Alignment(vertical="center", horizontal="center", wrap_text=True)

    ws["A2"] = "No-wrap Text"
    ws["A2"].alignment = Alignment(vertical="top", wrap_text=False)

    html_out = FastHtmlRenderer.render(ws)

    assert "vertical-align: middle" in html_out
    assert "white-space: normal; word-break: break-word" in html_out
    assert "vertical-align: top" in html_out
    assert "white-space: nowrap; overflow: hidden; text-overflow: ellipsis" in html_out

def test_template_processor_preserves_row_heights_in_loops():
    """Verify that repeated rows generated by {{#each ...}} inherit the source row's height."""
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "TestSheet"
    ws["A1"] = "Header"
    ws.row_dimensions[1].height = 25.0

    ws["A2"] = "{{#each items}}"
    ws["A3"] = "{{name}}"
    ws.row_dimensions[3].height = 28.5  # Detail row has custom 28.5pt height
    ws["A4"] = "{{/each}}"

    ws.column_dimensions["A"].width = 30.0

    processor = TemplateProcessor(wb)
    data = {"items": [{"name": "Alice"}, {"name": "Bob"}, {"name": "Charlie"}]}
    populated_wb = processor.process(data)
    populated_ws = populated_wb.active

    # Row 1 is header (height 25.0)
    assert populated_ws.row_dimensions[1].height == 25.0
    # Rows 2, 3, 4 are the 3 emitted item rows, each must have height 28.5
    assert populated_ws.row_dimensions[2].height == 28.5
    assert populated_ws.row_dimensions[3].height == 28.5
    assert populated_ws.row_dimensions[4].height == 28.5

    # Check HTML output
    html_out = FastHtmlRenderer.render(populated_ws)
    assert '<tr style="height: 25.0pt;">' in html_out
    assert '<tr style="height: 28.5pt;">' in html_out

def test_cdp_pdf_with_row_height_and_column_width():
    """Verify that Chrome CDP can render HTML with custom table-layout fixed, colgroup, and row heights."""
    if not ChromeCdpPool.is_available():
        return

    wb = openpyxl.Workbook()
    ws = wb.active
    ws["A1"] = "Item"
    ws["B1"] = "Price"
    ws.column_dimensions["A"].width = 25.0
    ws.column_dimensions["B"].width = 15.0
    ws.row_dimensions[1].height = 30.0

    ws["A2"] = "Widget A"
    ws["B2"] = 99.99
    ws.row_dimensions[2].height = 22.0

    html_out = FastHtmlRenderer.render(ws)
    pdf_bytes = ChromeCdpPool.render_html_to_pdf(html_out)
    assert pdf_bytes.startswith(b"%PDF-")
    assert len(pdf_bytes) > 1000
